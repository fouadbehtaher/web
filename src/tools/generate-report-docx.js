const fs = require("fs");
const path = require("path");

const ROOT_DIR = path.resolve(__dirname, "..", "..");
const SOURCE_MD = path.join(ROOT_DIR, "final-report-finalized.md");
const BUILD_DIR = path.join(ROOT_DIR, "build", "final-report-docx");
const OUTPUT_DIR = path.join(ROOT_DIR, "dist");

function xmlEscape(text) {
  return String(text)
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&apos;");
}

function stripMarkdown(line) {
  return line
    .replace(/\[([^\]]+)\]\(([^)]+)\)/g, "$1 ($2)")
    .replace(/`([^`]+)`/g, "$1")
    .replace(/\*\*([^*]+)\*\*/g, "$1")
    .replace(/\*([^*]+)\*/g, "$1");
}

function buildParagraph(text, style = null) {
  const escaped = xmlEscape(text);
  const styleXml = style ? `<w:pPr><w:pStyle w:val="${style}"/></w:pPr>` : "";
  return `<w:p>${styleXml}<w:r><w:t xml:space="preserve">${escaped}</w:t></w:r></w:p>`;
}

function buildPageBreak() {
  return `<w:p><w:r><w:br w:type="page"/></w:r></w:p>`;
}

function markdownToDocumentXml(markdown) {
  const lines = markdown.replace(/\r\n/g, "\n").split("\n");
  const paragraphs = [];

  lines.forEach((rawLine) => {
    const line = stripMarkdown(rawLine.trimEnd());

    if (!line.trim()) {
      paragraphs.push(`<w:p/>`);
      return;
    }

    if (line === "---PAGEBREAK---") {
      paragraphs.push(buildPageBreak());
      return;
    }

    if (line.startsWith("# ")) {
      paragraphs.push(buildParagraph(line.slice(2), "Title"));
      return;
    }

    if (line.startsWith("## ")) {
      paragraphs.push(buildParagraph(line.slice(3), "Heading1"));
      return;
    }

    if (line.startsWith("### ")) {
      paragraphs.push(buildParagraph(line.slice(4), "Heading2"));
      return;
    }

    if (/^\d+\.\s+/.test(line) || line.startsWith("- ")) {
      paragraphs.push(buildParagraph(line, "ListParagraph"));
      return;
    }

    paragraphs.push(buildParagraph(line, "Normal"));
  });

  return `<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<w:document xmlns:wpc="http://schemas.microsoft.com/office/word/2010/wordprocessingCanvas"
  xmlns:mc="http://schemas.openxmlformats.org/markup-compatibility/2006"
  xmlns:o="urn:schemas-microsoft-com:office:office"
  xmlns:r="http://schemas.openxmlformats.org/officeDocument/2006/relationships"
  xmlns:m="http://schemas.openxmlformats.org/officeDocument/2006/math"
  xmlns:v="urn:schemas-microsoft-com:vml"
  xmlns:wp14="http://schemas.microsoft.com/office/word/2010/wordprocessingDrawing"
  xmlns:wp="http://schemas.openxmlformats.org/drawingml/2006/wordprocessingDrawing"
  xmlns:w10="urn:schemas-microsoft-com:office:word"
  xmlns:w="http://schemas.openxmlformats.org/wordprocessingml/2006/main"
  xmlns:w14="http://schemas.microsoft.com/office/word/2010/wordml"
  xmlns:w15="http://schemas.microsoft.com/office/word/2012/wordml"
  xmlns:wpg="http://schemas.microsoft.com/office/word/2010/wordprocessingGroup"
  xmlns:wpi="http://schemas.microsoft.com/office/word/2010/wordprocessingInk"
  xmlns:wne="http://schemas.microsoft.com/office/word/2006/wordml"
  xmlns:wps="http://schemas.microsoft.com/office/word/2010/wordprocessingShape"
  mc:Ignorable="w14 w15 wp14">
  <w:body>
    ${paragraphs.join("")}
    <w:sectPr>
      <w:pgSz w:w="12240" w:h="15840"/>
      <w:pgMar w:top="1440" w:right="1440" w:bottom="1440" w:left="1440" w:header="708" w:footer="708" w:gutter="0"/>
    </w:sectPr>
  </w:body>
</w:document>`;
}

